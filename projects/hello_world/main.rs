// It uses the classic main entry function
// fn is the function declaration keyword
fn main() {
    // Here is the first thing to be noticed, the ! at the function call, it means it is not a
    // function call at all, it is indeed a macro call. Will learn more about that later.
    println!("Hello, world!");
}

